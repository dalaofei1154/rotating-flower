def support_root():
    return Path(os.environ.get('LOCALAPPDATA', str(Path.home() / 'AppData/Local'))) / 'RotatingFlower'


@contextmanager
def install_step(root, stage):
    """Best-effort diagnostics; never replace the original installation error."""
    def record(event, error=None):
        value = {'time': dt.datetime.now().astimezone().isoformat(), 'stage': stage, 'event': event}
        if error is not None:
            value.update(error_type=type(error).__name__, message=str(error))
            for name in ('errno', 'winerror', 'filename', 'filename2'):
                field = getattr(error, name, None)
                if field is not None:
                    value[name] = str(field) if isinstance(field, Path) else field
        try:
            logs = root / 'logs'
            logs.mkdir(parents=True, exist_ok=True)
            with (logs / 'install-events.jsonl').open('a', encoding='utf-8') as output:
                output.write(json.dumps(value, ensure_ascii=False) + '\n')
        except OSError:
            pass  # The support directory itself may be denied.
    record('begin')
    try:
        yield
    except BaseException as exc:
        record('failed', exc)
        if sys.stderr:
            print(f'安装步骤失败 [{stage}]：{exc}', file=sys.stderr)
        raise
    else:
        record('completed')


def acquire_lock(path):
    # Delayed import lets packaging run on a non-Windows development machine.
    sys.path.insert(0, str(Path(__file__).resolve().parent / 'integrated'))
    from platform_support import acquire_lock as lock
    return lock(path)


def write_json(path, value):
    temp = path.with_suffix('.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    temp.replace(path)


def read_config(root):
    try:
        value = json.loads((root / 'config.json').read_text(encoding='utf-8'))
    except FileNotFoundError:
        return None
    if not isinstance(value, dict) or value.get('schema') != 1:
        raise ValueError('Unsupported Windows installation configuration')
    settings = value.get('settings', {})
    if settings.get('source') not in SOURCES or type(settings.get('dry_run')) is not bool:
        raise ValueError('Invalid Windows source configuration')
    runtime = Path(value['runtime'])
    if runtime.parent.resolve() != (root / 'runtimes').resolve():
        raise ValueError('Runtime must be inside the installation directory')
    return value


def merged_settings(previous, args):
    prior = previous.get('settings', {}) if previous else {}
    defaults = {
        'source': 'both', 'sessions_root': str(Path(os.environ.get('CODEX_HOME', str(Path.home() / '.codex'))) / 'sessions'),
        'workbuddy_root': str(next((p for p in (Path.home() / '.workbuddy', Path.home() / '.workbuddy-ai')
                                   if (p / 'workbuddy.db').is_file()), Path.home() / '.workbuddy')),
        'qoder_root': str(Path.home() / '.qoder-cn'), 'qoder_app_data': None,
        'claude_root': None,
        'codex_endpoint': None, 'port': 'auto', 'dry_run': True,
    }
    result = {**defaults, **prior}
    for name in defaults:
        value = getattr(args, name, None)
        if value is not None:
            result[name] = str(value) if isinstance(value, Path) else value
    if result['source'] not in SOURCES:
        raise ValueError('Unknown Windows source selection')
    for name in ('sessions_root', 'workbuddy_root', 'qoder_root'):
        result[name] = str(Path(result[name]).expanduser().resolve())
    if result['qoder_app_data'] is not None:
        result['qoder_app_data'] = str(Path(result['qoder_app_data']).expanduser().resolve())
    result['claude_root'] = str(resolve_claude_root(result['claude_root']))
    return result


def bridge_command(root, config, *, once=False, launch_id=''):
    runtime = Path(config['runtime'])
    command = [str(runtime / 'venv/Scripts/python.exe'), '-E', '-s', '-X', 'utf8', '-u',
               str(runtime / 'app/integrated/integrated_bridge.py')]
    settings = config['settings']
    for key in ('source', 'sessions_root', 'workbuddy_root', 'port'):
        command += ['--' + key.replace('_', '-'), settings[key]]
    for key in ('qoder_root', 'qoder_app_data', 'claude_root'):
        if settings.get(key):
            command += ['--' + key.replace('_', '-'), settings[key]]
    if settings.get('codex_endpoint'):
        command += ['--codex-endpoint', settings['codex_endpoint']]
    if once:
        command += ['--once']
    else:
        command += ['--status-file', str(root / 'status.json'), '--attention-cache', str(root / 'attention-cache.json'),
                    '--stop-file', str(root / 'stop.request'), '--launch-id', launch_id]
        if settings['dry_run']:
            command += ['--dry-run']
    return command


def runner_command(config):
    runtime = Path(config['runtime'])
    return [str(runtime / 'venv/Scripts/pythonw.exe'), '-E', '-s', '-X', 'utf8',
            str(runtime / 'app/windows_setup.py'), 'run']


def autostart_command(root, pythonw=None):
    # Run values have a 260-character limit. A stable script avoids repeating
    # two long, versioned venv paths; its base Python is already required by venv.
    executable = Path(pythonw) if pythonw else Path(sys.base_prefix) / 'pythonw.exe'
    command = subprocess.list2cmdline([str(executable), '-E', '-s', '-X', 'utf8', str(root / 'boot.pyw')])
    if len(command.encode('utf-16-le')) // 2 > 260:
        raise ValueError('登录自启命令超过 Windows 的 260 字符上限；请将基础 Python 安装到较短路径后重试。')
    if sys.platform == 'win32' and not executable.is_file():
        raise ValueError('未找到基础 Python 的 pythonw.exe，无法设置登录自启。')
    return command


def get_autostart():
    import winreg
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, RUN_KEY) as key:
            return winreg.QueryValueEx(key, RUN_VALUE)[0]
    except FileNotFoundError:
        return None


def set_autostart(command):
    import winreg
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, RUN_KEY) as key:
        if command is None:
            try:
                winreg.DeleteValue(key, RUN_VALUE)
            except FileNotFoundError:
                pass
        else:
            winreg.SetValueEx(key, RUN_VALUE, 0, winreg.REG_SZ, command)


def runner_active(root):
    try:
        handle = acquire_lock(root / 'run.lock')
    except (BlockingIOError, PermissionError):
        return True
    handle.close()
    return False


def stop_and_lock(root, seconds=20):
    """Hold the runner lock before changing active files. Never kill a PID."""
    (root / 'stop.request').write_text('stop\n', encoding='ascii')
    deadline = time.monotonic() + seconds
    while True:
        try:
            return acquire_lock(root / 'run.lock')
        except (BlockingIOError, PermissionError):
            if time.monotonic() >= deadline:
                raise RuntimeError('后台未在时限内退出；已停止操作，未强制结束任何进程。')
            time.sleep(.2)


def prepare_runtime(root):
    source = Path(__file__).resolve().parent
    required = tuple('integrated/' + name for name in BRIDGE_FILES) + APP_FILES
    missing = [name for name in required if not (source / name).is_file()]
    if missing:
        raise ValueError('Missing bridge files: ' + ', '.join(missing))
    runtime = root / 'runtimes' / (dt.datetime.now().strftime('%Y%m%d-%H%M%S-') + uuid.uuid4().hex[:8])
    app = runtime / 'app'
    (app / 'integrated').mkdir(parents=True)
    try:
        for name in required:
            target = app / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source / name, target)
        with install_step(root, 'create-virtual-environment'):
            subprocess.run([sys.executable, '-m', 'venv', str(runtime / 'venv')], check=True, timeout=180)
        python = runtime / 'venv/Scripts/python.exe'
        with install_step(root, 'install-serial-dependency'):
            subprocess.run([str(python), '-m', 'pip', '--disable-pip-version-check', 'install',
                            '--require-hashes', '--only-binary=:all:',
                            '-r', str(app / 'windows/requirements.txt')], check=True, timeout=600)
        with install_step(root, 'verify-serial-dependency'):
            subprocess.run([str(python), '-I', '-c', 'import serial; import serial.tools.list_ports'],
                           check=True, timeout=20)
    except BaseException:
        shutil.rmtree(runtime, ignore_errors=True)
        raise
    return runtime


def launch(root, config):
    # Caller already stopped the old runner and committed configuration.
    # Invalidate prior receipts before the new runner gets CPU time.
    write_json(root / 'run.json', {'launch_id': 'starting-' + uuid.uuid4().hex, 'started_at': time.time()})
    (root / 'stop.request').unlink(missing_ok=True)
    return subprocess.Popen(runner_command(config), stdin=subprocess.DEVNULL,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                            creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0), close_fds=True)


def dsh_transaction(root, backup, plugin=None):
    change = DshPluginChange(Path.home() / '.dsh', root / 'dsh', plugin, backup=backup)
    if plugin is None:
        # A non-DSH install must not touch a manually managed observer. Legacy
        # preview installations have markers but no receipt; upgrades accept both.
        content = change.patch.read_bytes() if change.patch.exists() else b''
        if b'# BEGIN ROTATING-FLOWER DSH OBSERVER' not in content and not change.receipt.exists():
            return None
    return change


def install(root, args):
    previous = read_config(root)
    settings = merged_settings(previous, args)
    dsh_home = os.environ.get('DSH_HOME')
    if ('dsh' in enabled_sources(settings['source']) and dsh_home
            and Path(dsh_home).expanduser().resolve() != (Path.home() / '.dsh').resolve()):
        raise ValueError('本轮 DSH 仅支持默认目录 ~/.dsh 的 desktop profile；'
                         '检测到自定义 DSH_HOME，未安装或改变后台，请反馈实际 DSH 目录。')
    new_run = autostart_command(root)  # Reject overlong Run values before changing anything.
    old_run = get_autostart()
    old_bytes = (root / 'config.json').read_bytes() if previous else None
    boot = root / 'boot.pyw'
    old_boot = boot.read_bytes() if boot.exists() else None
    old_stopped = (root / 'stop.request').exists()
    with install_step(root, 'prepare-runtime'):
        runtime = prepare_runtime(root)  # Download failure must not stop the old service.
    config = {'schema': 1, 'version': VERSION, 'runtime': str(runtime), 'settings': settings}
    was_running = runner_active(root)
    guard = None
    stopped = False
    changed = False
    launch_attempted = False
    process = None
    dsh_change = None
    backup = root / 'backups' / runtime.name
    try:
        with install_step(root, 'stop-previous-runner'):
            guard = stop_and_lock(root)
        stopped = True
        backup.mkdir(parents=True)
        if old_bytes:
            (backup / 'config.json').write_bytes(old_bytes)
        if old_boot is not None:
            (backup / 'boot.pyw').write_bytes(old_boot)
        write_json(backup / 'autostart.json', {'command': old_run})
        plugin = (runtime / 'app/dsh/flower-observer.mjs'
                  if 'dsh' in enabled_sources(settings['source']) else None)
        # The helper only removes our marked block when DSH is not selected.
        # Keep the object before apply: partial writes also need rollback.
        dsh_change = dsh_transaction(root, backup, plugin)
        with install_step(root, 'configure-dsh-plugin'):
            if dsh_change is not None:
                dsh_change.apply()
        changed = True
        with install_step(root, 'commit-config-and-autostart'):
            write_json(root / 'config.json', config)
            boot.write_text(BOOTSTRAP, encoding='utf-8')
            set_autostart(new_run)
        guard.close()
        guard = None
        launch_attempted = True
        started_after = time.time()
        with install_step(root, 'start-and-check-runner'):
            process = launch(root, config)
            if wait_started(root, started_after=started_after) != 0:
                raise RuntimeError('新版本后台启动检查未通过。')
    except BaseException as failure:
        if launch_attempted:
            # Retain failed-version evidence before restoring old receipts.
            write_json(backup / 'failed-install.json', {'error': str(failure), 'configuration': config})
            try:
                guard = stop_and_lock(root)
                # A new process may not yet have acquired run.lock. Holding it
                # plus waiting on our own process handle closes that race.
                if process is not None:
                    process.wait(timeout=20)
                for name in ('status.json', 'run.json'):
                    if (root / name).is_file():
                        shutil.copy2(root / name, backup / ('failed-' + name))
            except (OSError, RuntimeError, subprocess.TimeoutExpired) as stop_error:
                if guard is not None:
                    guard.close()
                    guard = None
                raise RuntimeError('新版本未确认停止，暂未恢复旧配置或启动旧服务；已保留备份和日志。') from stop_error
        try:
            if guard is not None:
                try:
                    if dsh_change is not None:
                        dsh_change.rollback()
                finally:
                    if changed:
                        if old_bytes:
                            (root / 'config.json').write_bytes(old_bytes)
                        else:
                            (root / 'config.json').unlink(missing_ok=True)
                        if old_boot is not None:
                            boot.write_bytes(old_boot)
                        else:
                            boot.unlink(missing_ok=True)
                        set_autostart(old_run)
        finally:
            if guard is not None:
                guard.close()
                guard = None
        if not launch_attempted:
            shutil.rmtree(runtime)
        if stopped and previous and was_running:
            started_after = time.time()
            launch(root, previous)
            if wait_started(root, started_after=started_after) != 0:
                raise RuntimeError('已恢复旧配置和登录自启，但旧后台未通过重启检查；请查看日志。') from failure
        elif stopped and not old_stopped:
            (root / 'stop.request').unlink(missing_ok=True)
        raise
    finally:
        if guard is not None:
            guard.close()
    print('Windows 软件预览版已安装，并设置当前用户登录自启。')
    print('模式：' + ('软件检查（不连接 USB）' if settings['dry_run'] else 'USB 联动（等待实机验证）'))
    print('来源：' + settings['source'])
    if 'dsh' in enabled_sources(settings['source']):
        print('DSH 插件已配置到原生桌面 desktop profile；请重启 DSH 后创建新任务验证。')
    print('日志：' + str(root / 'logs/bridge.log'))
    return 0


def status(root):
    config = read_config(root)
    result = {'installed': config is not None, 'running': runner_active(root),
              'settings': config['settings'] if config else None, 'status_current': False, 'sources': {}}
    try:
        receipt = json.loads((root / 'run.json').read_text(encoding='utf-8'))
        state = read_status_snapshot(root / 'status.json')
        age = time.time() - state['updated_at']
        current = (result['running'] and state.get('launch_id') == receipt['launch_id'] and
                   -2 <= age < 8 and state['updated_at'] >= receipt['started_at'])
        if current:
            result.update(status_current=True, sources=state.get('sources', {}),
                          launch_id=receipt['launch_id'], started_at=receipt['started_at'],
                          motor=state.get('motor'), light=state.get('light'),
                          device_count=state.get('device_count', 0), dry_run=state.get('dry_run'))
    except PermissionError as exc:
        result['status_read_error'] = str(exc)
    except (OSError, ValueError, TypeError, KeyError):
        pass
    return result


def installation_diagnostics(root, config):
    """Read the same registry key used by this installer; do not change it."""
    runtime = Path(config['runtime'])
    result = {'installer_python': sys.executable, 'base_python_directory': sys.base_prefix,
              'installed_python': str(runtime / 'venv/Scripts/python.exe'),
              'installed_python_exists': (runtime / 'venv/Scripts/python.exe').is_file(),
              'autostart_registry_key': 'HKEY_CURRENT_USER\\' + RUN_KEY,
              'autostart_value_name': RUN_VALUE}
    try:
        result['autostart_command'] = get_autostart()
        result['autostart_registered'] = result['autostart_command'] is not None
    except OSError as exc:
        result['autostart_query_error'] = str(exc)
    return result


def wait_started(root, seconds=12, *, started_after=None):
    deadline = time.monotonic() + seconds
    while True:
        report = status(root)
        if report['status_current'] and (started_after is None or report.get('started_at', 0) >= started_after):
            print('后台已启动；以下结果仅报告软件状态，不代表硬件验收通过。')
            print(json.dumps(report, ensure_ascii=False, indent=2))
            return 0
        if time.monotonic() >= deadline:
            if 'status_read_error' in report:
                print(report['status_read_error'], file=sys.stderr)
            print('后台启动检查未通过；请查看日志后运行检查。', file=sys.stderr)
            return 3
        time.sleep(.3)


def run(root):
    """Login runner owns its lock for the full lifetime of the bridge child."""
    guard = acquire_lock(root / 'run.lock')
    try:
        if (root / 'stop.request').exists():
            return 0
        config = read_config(root)
        if not config:
            return 0
        logs = root / 'logs'
        logs.mkdir(exist_ok=True)
        with (logs / 'bridge.log').open('ab', buffering=0) as log:
            # Bounded retries handle transient startup failures without a crash loop.
            for attempt in range(4):
                if (root / 'stop.request').exists():
                    return 0
                launch_id = str(uuid.uuid4())
                write_json(root / 'run.json', {'launch_id': launch_id, 'started_at': time.time()})
                child = subprocess.Popen(bridge_command(root, config, launch_id=launch_id),
                                         stdin=subprocess.DEVNULL, stdout=log, stderr=subprocess.STDOUT,
                                         creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0), close_fds=True)
                result = child.wait()
                if result == 0 or (root / 'stop.request').exists():
                    return result
                log.write(f'Bridge exited with {result}; attempt {attempt + 1}/4.\n'.encode('utf-8'))
                if attempt < 3:
                    time.sleep(2 ** attempt)
            return result
    finally:
        guard.close()


def uninstall(root):
    previous = read_config(root)
    old_bytes = (root / 'config.json').read_bytes() if previous else None
    old_run = get_autostart()
    backup = root / 'backups' / ('uninstall-' + uuid.uuid4().hex[:8])
    with closing(stop_and_lock(root)):
        change = dsh_transaction(root, backup)
        try:
            if change is not None:
                change.apply()
            backup.mkdir(parents=True, exist_ok=True)
            write_json(backup / 'autostart.json', {'command': old_run})
            set_autostart(None)
            if previous:
                shutil.move(str(root / 'config.json'), str(backup / 'config.json'))
        except BaseException:
            try:
                if change is not None:
                    change.rollback()
            finally:
                if old_bytes is not None:
                    (root / 'config.json').write_bytes(old_bytes)
                set_autostart(old_run)
            # A failed uninstall remains paused; never restart a service here.
            raise
    print('已停止小花后台、移除登录自启和受管 DSH 插件配置；运行文件、备份和日志保留。')
    return 0


def make_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('install', 'start', 'stop', 'status', 'diagnose', 'uninstall', 'run'))
    parser.add_argument('--source', choices=SOURCES)
    parser.add_argument('--sessions-root', type=Path)
    parser.add_argument('--workbuddy-root', type=Path)
    parser.add_argument('--qoder-root', type=Path)
    parser.add_argument('--qoder-app-data', type=Path)
    parser.add_argument('--claude-root', type=Path)
    parser.add_argument('--codex-endpoint')
    parser.add_argument('--port')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--dry-run', dest='dry_run', action='store_true')
    mode.add_argument('--enable-hardware', dest='dry_run', action='store_false')
    parser.set_defaults(dry_run=None)
    return parser


def main(argv=None):
    parser = make_parser()
    args = parser.parse_args(argv)
    if sys.platform != 'win32':
        parser.error('此安装器仅在 Windows 运行；在 Mac 上可使用 package_windows.py 构建 ZIP。')
    if sys.version_info < (3, 11):
        parser.error('需要 Python 3.11 或更新版本。')
    for stream in (sys.stdout, sys.stderr):
        if stream and hasattr(stream, 'reconfigure'):
            stream.reconfigure(encoding='utf-8')
    root = support_root()
    try:
        with install_step(root, args.action) if args.action in ('install', 'uninstall') else nullcontext():
            root.mkdir(parents=True, exist_ok=True)
            if args.action == 'run':
                return run(root)
            with closing(acquire_lock(root / 'installer.lock')):
                if args.action == 'install':
                    return install(root, args)
                if args.action == 'uninstall':
                    return uninstall(root)
                if args.action == 'stop':
                    with closing(stop_and_lock(root)):
                        print('后台已停止；登录自启设置保留。')
                    return 0
                if args.action == 'status':
                    print(json.dumps(status(root), ensure_ascii=False, indent=2))
                    return 0
                config = read_config(root)
                if not config:
                    raise RuntimeError('尚未安装小花，请先运行安装。')
                if args.action == 'diagnose':
                    print(json.dumps({'installation': installation_diagnostics(root, config)}, ensure_ascii=False, indent=2))
                    return subprocess.run(bridge_command(root, config, once=True), check=False).returncode
                started_after = None
                if (root / 'stop.request').exists():
                    with closing(stop_and_lock(root)):
                        pass
                    started_after = time.time()
                    launch(root, config)
                elif not runner_active(root):
                    started_after = time.time()
                    launch(root, config)
                return wait_started(root, started_after=started_after)
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        message = '未完成：' + str(exc)
        if sys.stderr:
            print(message, file=sys.stderr)
        else:
            logs = root / 'logs'
            logs.mkdir(exist_ok=True)
            with (logs / 'runner-error.log').open('a', encoding='utf-8') as output:
                output.write(message + '\n')
        return 1


if __name__ == '__main__':
    sys.exit(main())
